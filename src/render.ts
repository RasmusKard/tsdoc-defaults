// Renders the `.defaults.ts` module text: deterministic, 2-space indent, `\n`, source order, quoted names kept.
import ts from 'typescript';
import { parseExpression } from './expressions.js';
import type { ExtractResult } from './index.js';

/** Indexes of the lines that start inside a template literal; re-indenting one would change the string. */
function templateLines(expr: string): Set<number> {
  const sf = parseExpression(expr);
  const lines = new Set<number>();
  const visit = (n: ts.Node): void => {
    if (ts.isTemplateLiteralToken(n)) {
      const first = sf.getLineAndCharacterOfPosition(n.getStart(sf)).line;
      const last = sf.getLineAndCharacterOfPosition(n.end).line;
      for (let l = first + 1; l <= last; l++) lines.add(l);
    }
    n.forEachChild(visit);
  };
  visit(sf);
  return lines;
}

/** One `key: expr,` line; continuation lines of a multi-line expression are re-indented to sit inside the object. */
function renderMember(key: string, expr: string): string {
  const lines = expr.split('\n');
  const fixed = templateLines(expr);
  const movable = (l: string, i: number) => i > 0 && !fixed.has(i) && l.trim();
  const margin = Math.min(
    ...lines.filter(movable).map((l) => /^ */.exec(l)![0].length),
  );
  const body = lines.map((l, i) =>
    movable(l, i) ? `    ${l.slice(margin)}` : i === 0 || fixed.has(i) ? l : '',
  );
  return `    ${key}: ${body.join('\n')},`;
}

// A numeric key is a number in `keyof`, so it stays unquoted.
const pickKey = (member: string) =>
  /^['"\d]/.test(member) ? member : `'${member}'`;

/** The module text for `source` (a file name without directories), importing its types from `specifier`. */
export function renderModule(
  source: string,
  specifier: string,
  result: Pick<ExtractResult, 'members' | 'imports' | 'directives'>,
): string {
  const names = [...new Set(result.members.map((m) => m.declaration))];
  const decls = names.map(
    (n) => [n, result.members.filter((m) => m.declaration === n)] as const,
  );
  // A type annotation, not `satisfies`: react-docgen does not unwrap `satisfies` when resolving `DEFAULTS.T.x`.
  return [
    `// Generated by tsdoc-defaults from the @default/@defaultValue tags in ./${source}. Do not edit.`,
    `import type { ${names.join(', ')} } from '${specifier}';`,
    ...result.imports,
    ...result.directives,
    '',
    'export const DEFAULTS: {',
    ...decls.map(
      ([n, ms]) =>
        `  ${n}: Required<Pick<${n}, ${ms.map((m) => pickKey(m.member)).join(' | ')}>>;`,
    ),
    '} = {',
    ...decls.flatMap(([n, ms]) => [
      `  ${n}: {`,
      ...ms.map((m) => renderMember(m.member, m.expression)),
      '  },',
    ]),
    '};',
    '',
  ].join('\n');
}
