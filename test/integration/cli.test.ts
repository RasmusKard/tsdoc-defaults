import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const root = path.resolve(fileURLToPath(import.meta.url), '../../..');
const fx = path.join(root, 'test/fixtures');
const bin = (name: string) => path.join(root, 'node_modules/.bin', name);
const run = (cmd: string, args: string[], cwd = root) => {
  const r = spawnSync(bin(cmd), args, { cwd, encoding: 'utf8' });
  return { code: r.status, out: r.stdout + r.stderr };
};
const cli = (...args: string[]) => run('tsx', ['src/cli.ts', ...args]);
const cliIn = (cwd: string, ...args: string[]) =>
  run('tsx', [path.join(root, 'src/cli.ts'), ...args], cwd);
const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'tsdoc-defaults-'));
const member = (tag: string) =>
  `export interface Opts {\n  /** @default ${tag} */\n  x?: number;\n}\n`;

const BASIC = `// Generated by tsdoc-defaults from the @default/@defaultValue tags in ./basic.ts. Do not edit.
import type { BridgeOptions, IOSOptions, Theme } from './basic';

export const DEFAULTS: {
  BridgeOptions: Required<Pick<BridgeOptions, 'timeoutMs' | 'fit' | 'webView' | 'logLevel' | 'data-enabled'>>;
  IOSOptions: Required<Pick<IOSOptions, 'bounces'>>;
  Theme: Required<Pick<Theme, 'mode' | 'fontSize'>>;
} = {
  BridgeOptions: {
    timeoutMs: 10_000,
    fit: 'cover',
    webView: { customUserAgent: null, inspectable: __DEV__ },
    logLevel: __DEV__ ? 'debug' : 'warn',
    'data-enabled': true,
  },
  IOSOptions: {
    bounces: false,
  },
  Theme: {
    mode: 'light',
    fontSize: 14,
  },
};
`;

const IMPORTS = `// Generated by tsdoc-defaults from the @default/@defaultValue tags in ./imports.ts. Do not edit.
import type { ImportOptions } from './imports';
import { Foo } from './foo';
import { Platform } from './platform'

export const DEFAULTS: {
  ImportOptions: Required<Pick<ImportOptions, 'foo' | 'retry' | 'bounces'>>;
} = {
  ImportOptions: {
    foo: Foo.BAR,
    retry: {
      attempts: 3,
      backoff: (n: number) => n * 2,
    },
    bounces: Platform.OS === 'ios',
  },
};
`;

const tsc = (dir: string, ...files: string[]) =>
  run(
    'tsc',
    [
      '--noEmit',
      '--strict',
      '--module',
      'preserve',
      '--moduleResolution',
      'bundler',
      ...files,
    ],
    dir,
  );

const checkBasic = () =>
  cli('--check', '-p', 'test/fixtures/tsconfig.json', 'test/fixtures/basic.ts');

const generateFixtures = () =>
  assert.equal(
    cli(
      '-p',
      'test/fixtures/tsconfig.json',
      'test/fixtures/basic.ts',
      'test/fixtures/imports.ts',
    ).code,
    0,
  );

void test('generates the expected modules', () => {
  generateFixtures();
  assert.equal(
    fs.readFileSync(path.join(fx, 'basic.defaults.ts'), 'utf8'),
    BASIC,
  );
  assert.equal(
    fs.readFileSync(path.join(fx, 'imports.defaults.ts'), 'utf8'),
    IMPORTS,
  );
  const r = run('tsc', ['-p', 'test/fixtures/tsconfig.json']);
  assert.equal(r.code, 0, r.out);
});

void test('globs match sources and never generated files; no match, or no args without a tsconfig.json, is a usage error; --help is not', () => {
  const dir = tmp();
  fs.copyFileSync(path.join(fx, 'basic.ts'), path.join(dir, 'basic.ts'));
  assert.equal(cli(path.join(dir, '**/*.ts')).code, 0);
  assert.equal(cli(path.join(dir, '**/*.ts')).code, 0);
  assert.deepEqual(fs.readdirSync(dir).sort(), [
    'basic.defaults.ts',
    'basic.ts',
  ]);
  assert.equal(cli(path.join(dir, 'nothing/*.ts')).code, 2);
  assert.equal(cliIn(tmp()).code, 2);
  for (const flag of ['--help', '-h']) {
    const r = cli(flag);
    assert.equal(r.code, 0, flag);
    assert.match(r.out, /^usage: /, flag);
  }
  assert.equal(cli('--bogus', path.join(dir, 'basic.ts')).code, 2);
});

void test('the type annotation rejects a default of the wrong type', () => {
  const dir = tmp();
  fs.writeFileSync(
    path.join(dir, 'wrong.ts'),
    "export interface Opts {\n  /** @default `'ten'` */\n  timeoutMs?: number;\n}\n",
  );
  assert.equal(cli(path.join(dir, 'wrong.ts')).code, 0);
  const r = tsc(dir, 'wrong.defaults.ts');
  assert.notEqual(r.code, 0);
  assert.match(
    r.out,
    /wrong\.defaults\.ts.*Type 'string' is not assignable to type 'number'/s,
  );
});

void test('errors are reported as file:line:col with exit code 1, and nothing is written', () => {
  const r = cli('test/fixtures/errors/generic.ts');
  assert.equal(r.code, 1);
  assert.match(
    r.out,
    /generic\.ts:1:1 Generic: generic declarations are not supported/,
  );
  assert.equal(
    fs.existsSync(path.join(fx, 'errors/generic.defaults.ts')),
    false,
  );
});

void test('a leftover file for a source without defaults is stale, and generation removes it', () => {
  const dir = tmp();
  const file = path.join(dir, 'orphan.ts');
  fs.writeFileSync(file, member('`1`'));
  assert.equal(cli(file).code, 0);
  fs.writeFileSync(file, 'export interface Opts {\n  x?: number;\n}\n');
  const r = cli('--check', file);
  assert.equal(r.code, 1);
  assert.match(r.out, /orphan\.defaults\.ts is stale: run tsdoc-defaults/);
  assert.equal(cli(file).code, 0);
  assert.deepEqual(fs.readdirSync(dir), ['orphan.ts']);
  assert.equal(cli('--check', file).code, 0);
});

void test('a trailing line comment, a numeric key and a multi-line template literal compile', () => {
  const dir = tmp();
  fs.writeFileSync(
    path.join(dir, 'mixed.ts'),
    [
      'export interface Opts {',
      '  /** @default `10_000 // ten seconds` */',
      '  timeoutMs?: number;',
      '  /** @default `2` */',
      '  0?: number;',
      '  /**',
      '   * @default',
      '   * ```ts',
      '   * `line1',
      '   *   line2`',
      '   * ```',
      '   */',
      '  s?: string;',
      '}',
      '',
    ].join('\n'),
  );
  assert.equal(cli(path.join(dir, 'mixed.ts')).code, 0);
  const text = fs.readFileSync(path.join(dir, 'mixed.defaults.ts'), 'utf8');
  assert.match(text, /Pick<Opts, 'timeoutMs' \| 0 \| 's'>/);
  assert.match(text, /timeoutMs: 10_000,\n/);
  assert.match(text, /s: `line1\n  line2`,\n/);
  const r = tsc(dir, 'mixed.defaults.ts');
  assert.equal(r.code, 0, r.out);
});

void test('--check passes when fresh, ignores formatting, fails when stale or missing', () => {
  generateFixtures();
  const file = path.join(fx, 'basic.defaults.ts');
  assert.equal(checkBasic().code, 0);
  try {
    fs.writeFileSync(
      file,
      BASIC.replace('timeoutMs: 10_000,', 'timeoutMs:   10_000 ,').replace(
        '// Generated',
        '// edited',
      ),
    );
    assert.equal(checkBasic().code, 0);
    fs.writeFileSync(file, BASIC.replace('10_000', '20_000'));
    const r = checkBasic();
    assert.equal(r.code, 1);
    assert.match(r.out, /basic\.defaults\.ts is stale: run tsdoc-defaults/);
    fs.rmSync(file);
    assert.equal(checkBasic().code, 1);
  } finally {
    generateFixtures();
  }
});

void test('the tsconfig.json in the working directory picks the import extension, and the sources without globs', () => {
  const cases: [object, string][] = [
    [{ module: 'nodenext' }, './a.js'],
    [{ module: 'nodenext', allowImportingTsExtensions: true }, './a.ts'],
    [{ module: 'preserve', moduleResolution: 'bundler' }, './a'],
  ];
  for (const [compilerOptions, specifier] of cases) {
    const dir = tmp();
    fs.mkdirSync(path.join(dir, 'src'));
    fs.mkdirSync(path.join(dir, 'test'));
    fs.writeFileSync(path.join(dir, 'src/a.ts'), member('`1`'));
    // Outside `include`: its non-exported declaration would be an error.
    fs.writeFileSync(
      path.join(dir, 'test/b.ts'),
      member('`1`').replace('export ', ''),
    );
    fs.writeFileSync(
      path.join(dir, 'tsconfig.json'),
      JSON.stringify({ compilerOptions, include: ['src'] }),
    );
    const r = cliIn(dir);
    assert.equal(r.code, 0, r.out);
    const text = fs.readFileSync(path.join(dir, 'src/a.defaults.ts'), 'utf8');
    assert.match(text, new RegExp(`from '${specifier}';`), specifier);
    assert.equal(fs.existsSync(path.join(dir, 'test/b.defaults.ts')), false);
    assert.equal(cliIn(dir, '--check').code, 0);
  }
  const dir = tmp();
  fs.writeFileSync(path.join(dir, 'a.ts'), member('`1`'));
  fs.writeFileSync(
    path.join(dir, 'tsconfig.json'),
    JSON.stringify({ compilerOptions: { module: 'nodenext' }, include: [] }),
  );
  assert.equal(cliIn(dir, 'a.ts').code, 0);
  assert.match(
    fs.readFileSync(path.join(dir, 'a.defaults.ts'), 'utf8'),
    /from '\.\/a\.js';/,
  );
});

void test('--project reads its config relative to its own directory; a missing one is a usage error', () => {
  const dir = tmp();
  fs.mkdirSync(path.join(dir, 'pkg/src'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'pkg/src/a.ts'), member('`1`'));
  fs.writeFileSync(
    path.join(dir, 'pkg/tsconfig.build.json'),
    JSON.stringify({
      compilerOptions: { module: 'nodenext' },
      include: ['src'],
    }),
  );
  assert.equal(cliIn(dir, '-p', 'pkg/tsconfig.build.json').code, 0);
  assert.match(
    fs.readFileSync(path.join(dir, 'pkg/src/a.defaults.ts'), 'utf8'),
    /from '\.\/a\.js';/,
  );
  const r = cliIn(dir, '--project', 'nope.json');
  assert.equal(r.code, 2);
  assert.match(r.out, /^nope\.json: /);
});

void test('without globs, a tsconfig.json that includes no files or does not parse is a usage error', () => {
  for (const [config, message] of [
    ['{ "include": ["nothing"] }', /includes no TypeScript files: pass globs/],
    ['{', /tsconfig\.json: '\}' expected/],
    [
      '{ "compilerOptions": { "module": "bogus" } }',
      /tsconfig\.json: .*--module/,
    ],
  ] as const) {
    const dir = tmp();
    fs.writeFileSync(path.join(dir, 'tsconfig.json'), config);
    const r = cliIn(dir);
    assert.equal(r.code, 2, config);
    assert.match(r.out, message, config);
  }
});
